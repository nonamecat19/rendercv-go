func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "docprobe:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := repoRoot()
	if err != nil {
		return err
	}

	corpusDir := filepath.Join(workroot.Root, "run")
	cases, err := os.ReadDir(corpusDir)
	if err != nil {
		return fmt.Errorf("reading the corpus (run `just golden` first?): %w", err)
	}

	target := filepath.Join(root, outDir)
	if err := os.RemoveAll(target); err != nil {
		return err
	}

	var rendered, skipped []string
	for _, entry := range cases {
		if !entry.IsDir() {
			continue
		}
		name := entry.Name()

		input := filepath.Join(corpusDir, name, "cv.yaml")
		if _, err := os.Stat(input); err != nil {
			skipped = append(skipped, name+" (no cv.yaml)")
			continue
		}

		typ, err := renderCase(root, input)
		if err != nil {
			skipped = append(skipped, name+" ("+err.Error()+")")
			continue
		}

		dir := filepath.Join(target, name)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		raw, err := os.ReadFile(input)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, "cv.yaml"), raw, 0o644); err != nil {
			return err
		}
		if err := writeArtifacts(dir, typ); err != nil {
			return err
		}
		rendered = append(rendered, name)
	}

	for name, document := range extraCases {
		input, err := writeExtra(name, document)
		if err != nil {
			return err
		}
		typ, err := renderCase(root, input)
		if err != nil {
			return fmt.Errorf("extra case %s: %w", name, err)
		}

		dir := filepath.Join(target, name)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, "cv.yaml"), []byte(document), 0o644); err != nil {
			return err
		}
		if err := writeArtifacts(dir, typ); err != nil {
			return err
		}
		// The fixture has to carry the photo too: the conformance test validates
		// the input, and `cv.photo`'s existence check runs there as well.
		if err := copyImages(filepath.Dir(input), dir); err != nil {
			return err
		}
		rendered = append(rendered, name)
	}

	sort.Strings(rendered)
	sort.Strings(skipped)
	fmt.Printf("rendered %d cases into %s\n", len(rendered), outDir)
	for _, name := range skipped {
		fmt.Println("  skipped", name)
	}
	if len(rendered) == 0 {
		return fmt.Errorf("no case rendered; the fixture would be empty")
	}
	return nil
}

// writeExtra materializes one extra case's document so renderCase can treat it
// exactly like a corpus input.
func writeExtra(name, document string) (string, error) {
	dir, err := os.MkdirTemp("", "docprobe-extra-"+name+"-")
	if err != nil {
		return "", err
	}

	// `cv.photo` is an **existence-checked** path, so a case that names one has
	// to have one. The bytes are a PNG header and nothing reads them: neither
	// side decodes the image, and no case here compiles the Typst.
	if strings.Contains(document, "images/me.png") {
		images := filepath.Join(dir, "images")
		if err := os.MkdirAll(images, 0o755); err != nil {
			return "", err
		}
		png := []byte{0x89, 'P', 'N', 'G', '\r', '\n', 0x1a, '\n'}
		if err := os.WriteFile(filepath.Join(images, "me.png"), png, 0o644); err != nil {
			return "", err
		}
	}

	path := filepath.Join(dir, "cv.yaml")
	return path, os.WriteFile(path, []byte(document), 0o644)
}

// renderCase runs the vendored CLI in a scratch directory, so the corpus's own
// working tree is never written to, and returns the one `.typ` it produced.
func renderCase(root, input string) (artifacts, error) {
	scratch, err := os.MkdirTemp("", "docprobe-")
	if err != nil {
		return artifacts{}, err
	}
	defer func() { _ = os.RemoveAll(scratch) }()

	raw, err := os.ReadFile(input)
	if err != nil {
		return artifacts{}, err
	}
	copied := filepath.Join(scratch, "cv.yaml")
	if err := os.WriteFile(copied, raw, 0o644); err != nil {
		return artifacts{}, err
	}

	// `cv.photo` is resolved **relative to the input file** and its existence is
	// checked, so a case that names one needs its `images/` beside the copy.
	if err := copyImages(filepath.Dir(input), scratch); err != nil {
		return artifacts{}, err
	}

	cmd := exec.Command(
		"uv", "run", "--frozen", "--all-extras",
		"rendercv", "render", copied,
		"-nopdf", "-nopng",
		"--settings.current_date", CurrentDate,
	)
	cmd.Dir = filepath.Join(root, upstreamDir)
	if out, err := cmd.CombinedOutput(); err != nil {
		return artifacts{}, fmt.Errorf("upstream rejected it: %s", firstLine(out))
	}

	out := artifacts{}
	for extension, target := range map[string]*[]byte{
		"typ": &out.typ, "md": &out.markdown, "html": &out.html,
	} {
		matches, err := filepath.Glob(
			filepath.Join(scratch, "rendercv_output", "*."+extension))
		if err != nil {
			return artifacts{}, err
		}
		if len(matches) != 1 {
			return artifacts{}, fmt.Errorf("produced %d .%s files", len(matches), extension)
		}
		raw, err := os.ReadFile(matches[0])
		if err != nil {
			return artifacts{}, err
		}
		*target = raw
	}
	return out, nil
}

// artifacts are the three text documents one render produces. The PDF and the
// PNGs are iteration 10's and are not generated at all — they are slow, and
// their bytes carry timestamps that could never be compared this way.
type artifacts struct {
	typ, markdown, html []byte
}

// writeArtifacts stores the three documents beside the input they came from.
func writeArtifacts(dir string, out artifacts) error {
	for name, content := range map[string][]byte{
		"expected.typ": out.typ, "expected.md": out.markdown, "expected.html": out.html,
	} {
		if err := os.WriteFile(filepath.Join(dir, name), content, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// copyImages copies an `images/` directory beside the input, when there is one.
func copyImages(from, to string) error {
	entries, err := os.ReadDir(filepath.Join(from, "images"))
	if err != nil {
		return nil //nolint:nilerr // no images directory is the ordinary case
	}

	target := filepath.Join(to, "images")
	if err := os.MkdirAll(target, 0o755); err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(from, "images", entry.Name()))
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(target, entry.Name()), raw, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func firstLine(out []byte) string {
	text := strings.TrimSpace(string(out))
	if index := strings.IndexByte(text, '\n'); index >= 0 {
		text = text[:index]
	}
	if len(text) > 120 {
		text = text[:120]
	}
	return text
}

func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above %s", dir)
		}
		dir = parent
	}
}
