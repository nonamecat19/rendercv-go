// Command docprobe renders every corpus input with the vendored Python and
// stores the resulting `.typ`, `.md` and `.html` under
// internal/renderer/document/testdata/documents/<case>/, beside the input they
// came from.
//
// **This is the gate iterations 9 and 11 end at** (spec 009 §6, spec 011 §5):
// the Go renderer's output has to be byte-identical to these. It is a differential rather than a
// read of `testdata/golden`, for one reason — the goldens were generated on a
// particular day and carry that date in the preamble and the top note, while
// this pins `settings.current_date` so both sides are reproducible.
//
// **What this tool cannot check.** Only the cases it renders, and nothing here
// covers the Markdown or HTML documents.
//
// Twenty-two of the forty-three corpus cases are skipped. Nineteen have no
// `cv.yaml`: the `cli_*` and `err_*` cases, and — worth naming, because the
// earlier wording implied otherwise — `new_default`, `new_typst_templates` and
// `sample_entries`, whose input is `John_Doe_CV.yaml`. The first two carry the
// canonical sample CV, which nothing in this repo renders differentially. Three
// more are skipped because upstream itself rejects them (`err_empty_yaml`,
// `err_not_yaml`, `err_unknown_theme`).
//
// A Go failure cannot produce a skip: this tool never runs Go code.
//
// The fixture is GENERATED and is NEVER hand-written or hand-edited
// (AGENTS.md §10.1); this program is its only author. It is not part of
// testdata/golden, so regenerating it does not change the parity contract and
// needs no special approval.
//
// Usage:
//
//	go run ./tools/docprobe    # or: just docprobe
package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"github.com/nonamecat19/rendercv-go/internal/conformance/workroot"
)

const (
	upstreamDir = "third_party/rendercv"
	outDir      = "internal/renderer/document/testdata/documents"

	// CurrentDate is what every case is rendered with, so the preamble's
	// `datetime(...)` and the top note's month are the same on both sides and on
	// every day. It is the reference date the port's own tests already use.
	CurrentDate = "2025-03-05"
)

// extraCases are documents the corpus does not contain, kept here so they are
